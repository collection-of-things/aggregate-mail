import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { ImapFlow } from "imapflow";
import { google } from "./google-api.js";
import type { Mail } from "../shared/types.js";

test("single-message unread and inbox actions use confirmed provider identity and preserve local IDs", async t => {
 const directory = mkdtempSync(path.join(tmpdir(), "emc2-actions-"));
 process.env.MAIL_DATA_DIR = directory;
 process.env.MAIL_DATA_KEY = Buffer.alloc(32, 8).toString("base64");
 const { put, get, closeStore, syncMailCache } = await import("./store.js");
 const { providers } = await import("./providers.js");
 const { updateMessage } = await import("./mail-actions.js");
 t.after(() => { closeStore(); rmSync(directory, {recursive:true, force:true}); });
 const account = {id:"a", email:"reader@example.test", provider:"imap" as const, credentials:{imapHost:"imap.example.test", password:"synthetic"}};
 const mail: Mail = {id:"a:1:5", accountId:"a", remoteId:"1:5", sender:"Team", address:"team@example.test", to:account.email, subject:"Synthetic", body:"Body", preview:"Body", date:1, unread:false, archived:true, category:"important", relevance:2, reason:"", snoozedUntil:null, messageId:"<one@example.test>", pinned:true, mailbox:{path:"Saved",uidValidity:"1",uid:77}};
 put("account", account.id, account); put("mail", mail.id, mail);
 let capabilities = ["MOVE", "UIDPLUS"], matches = [77], source = "Saved", candidateId = mail.messageId, uid = 77;
 const mutations: string[] = [];
 t.mock.method(ImapFlow.prototype, "connect", async function(this: ImapFlow) {this.capabilities = new Map(capabilities.map(value => [value, true]));});
 t.mock.method(ImapFlow.prototype, "close", () => {});
 t.mock.method(ImapFlow.prototype, "list", async () => source ? [{path:source, specialUse:"\\Archive", flags:new Set(["\\Archive"])}] : []);
 t.mock.method(ImapFlow.prototype, "getMailboxLock", async function(this:ImapFlow, mailbox:string) {this.mailbox={path:mailbox, delimiter:"/", uidValidity:1n, uidNext:100, exists:1, flags:new Set()}; return {release(){}};});
 t.mock.method(ImapFlow.prototype, "search", async () => matches);
 t.mock.method(ImapFlow.prototype, "fetchOne", async () => ({seq:1, uid, headers:Buffer.from(`Message-ID: ${candidateId}\r\n\r\n`), envelope:{date:new Date(mail.date), subject:mail.subject}}));
 t.mock.method(ImapFlow.prototype, "messageFlagsRemove", async (target:string, flags:string[], options:object) => {assert.deepEqual(flags,["\\Seen"]); assert.deepEqual(options,{uid:true}); mutations.push(`unread:${target}`); return true;});
 t.mock.method(ImapFlow.prototype, "messageMove", async (target:string, destination:string) => {assert.equal(destination,"INBOX"); mutations.push(`inbox:${target}`);return {path:source,destination,uidValidity:1n,uidMap:new Map([[77,99]])};});
 await updateMessage(mail.id,{action:"unread"});
 assert.equal(get("mail",mail.id)?.unread,true); assert.deepEqual(mutations,["unread:77"]);
 for (const mailbox of [undefined, {path:"Saved",uidValidity:"2",uid:77}])
   await assert.rejects(providers.imap.update(account,{...mail,mailbox},"inbox"),/confirmed mailbox binding/);
 matches=[77]; candidateId="<other@example.test>"; await assert.rejects(updateMessage(mail.id,{action:"inbox"}),/Could not identify/);
 candidateId=mail.messageId; uid=78; await assert.rejects(updateMessage(mail.id,{action:"inbox"}),/Could not identify/); uid=77;
 source=""; await assert.rejects(updateMessage(mail.id,{action:"inbox"}),/unique archive/); source="Saved";
 capabilities=[]; await assert.rejects(updateMessage(mail.id,{action:"inbox"}),/does not support safe/); capabilities=["MOVE","UIDPLUS"];
 assert.deepEqual(mutations,["unread:77"]);
 await updateMessage(mail.id,{action:"inbox"});
 const restored=get("mail",mail.id)!; assert.equal(restored.archived,false); assert.equal(restored.remoteId,"1:99"); assert.equal(restored.pinned,true);
 const cache=await syncMailCache("a"); assert.equal(cache.get("a:1:99")?.id,mail.id); assert.equal(cache.size,1);
 assert.deepEqual(mutations,["unread:77","inbox:77"]);
 t.mock.method(ImapFlow.prototype, "fetch", async function* () { yield {seq:1,uid:99,flags:new Set<string>()}; });
 const synced = await providers.imap.list(account, cache);
 assert.equal(synced.length,1); assert.equal(synced[0].id,mail.id); assert.equal(synced[0].unread,true); assert.equal(synced[0].remoteId,"1:99");
 await assert.rejects(providers.imap.update(account,{...mail,direction:"sent"},"unread"),/unsupported/);
 const gmailImap={...account,provider:"gmail-imap" as const};
 source="[Gmail]/All Mail";
 t.mock.method(ImapFlow.prototype, "list", async () => [{path:source, specialUse:"\\All", flags:new Set(["\\All"])}]);
 t.mock.method(ImapFlow.prototype, "messageCopy", async (target:string, destination:string) => {assert.equal(destination,"INBOX"); mutations.push(`copy:${target}`);return {path:source,destination,uidValidity:1n,uidMap:new Map([[77,123]])};});
 capabilities=["UIDPLUS"];
 assert.deepEqual(await providers["gmail-imap"].update(gmailImap,{...mail,archived:true,mailbox:{path:source,uidValidity:"1",uid:77}},"inbox"),{remoteId:"1:123"});
 assert.deepEqual(mutations.slice(-1),["copy:77"], "Gmail IMAP copies into INBOX and never moves mail out of All Mail");
 const api=google.gmail("v1"); t.mock.method(google,"gmail",()=>api,{});
 const calls:unknown[]=[];t.mock.method(api.users.messages,"modify",async(input:unknown)=>{calls.push(input);return {data:{}};});
 const gmail={...account,provider:"gmail" as const,credentials:{refreshToken:"synthetic"}};
 await providers.gmail.update(gmail,mail,"unread"); await providers.gmail.update(gmail,mail,"inbox");
 put("account", account.id, gmail); put("mail", mail.id, {...mail,unread:false});
 await updateMessage(mail.id,{action:"unread"}); await updateMessage(mail.id,{action:"inbox"});
 assert.equal(get("mail",mail.id)?.unread,true); assert.equal(get("mail",mail.id)?.archived,false);
 t.mock.method(api.users.messages,"list",async()=>({data:{messages:[{id:"1:5"}]}}));
 const gmailCache=await syncMailCache("a");
 const gmailSynced=await providers.gmail.list(gmail,gmailCache);
 assert.equal(gmailSynced.length,1); assert.equal(gmailSynced[0].unread,true); assert.ok(gmailSynced[0].labelIds?.includes("INBOX"));
 assert.deepEqual(calls.slice(0,2),[{userId:"me",id:"1:5",requestBody:{addLabelIds:["UNREAD"]}},{userId:"me",id:"1:5",requestBody:{addLabelIds:["INBOX"]}}]);
});
